/**
 * كلمات مفتاحية للكشف الفوري عن أعراض طارئة/خطيرة في رسائل المريض.
 *
 * هذه شبكة أمان (safety net) مستقلة تماماً عن استجابة الذكاء الاصطناعي —
 * حتى لو فشل النموذج في وضع escalate=true، هذا الفحص النصي البسيط
 * يفرض التصعيد الفوري لطبيب حقيقي/الطوارئ. لا يجب الاعتماد على الذكاء
 * الاصطناعي وحده في قرارات قد تتعلق بحياة المريض.
 *
 * ⚠️ هذه قائمة أولية للتوضيح فقط — يجب مراجعتها وتوسيعها من طرف طاقم طبي
 * مختص قبل الاستخدام الفعلي في الإنتاج (تغطية لهجات جزائرية، مرادفات، إلخ).
 */
export const EMERGENCY_KEYWORDS: string[] = [
  'ألم في الصدر', 'ضيق تنفس', 'صعوبة في التنفس', 'نزيف حاد', 'فقدان وعي',
  'إغماء', 'شلل', 'تنميل مفاجئ', 'تشنجات', 'حروق شديدة', 'تسمم',
  'أفكار انتحارية', 'أريد أن أموت', 'أؤذي نفسي', 'ابتلاع دواء بكمية كبيرة',
  'حمى شديدة عند رضيع', 'نزيف أثناء الحمل', 'ألم بطن شديد مفاجئ',
];

export function containsEmergencyKeyword(text: string): boolean {
  const normalized = text.trim();
  return EMERGENCY_KEYWORDS.some((kw) => normalized.includes(kw));
}

