/**
 * يزيل التشكيل العربي (الحركات) ويوحّد المسافات المتعددة قبل المقارنة،
 * حتى لا يفوت الكشفَ اختلافٌ سطحي في كتابة نفس الرسالة من المريض.
 */
function normalizeArabicText(text: string): string {
  return text
    .replace(/[\u064B-\u065F\u0670]/g, '') // إزالة التشكيل
    .replace(/\s+/g, ' ')
    .trim();
}

export function containsEmergencyKeyword(text: string): boolean {
  const normalized = normalizeArabicText(text);
  return EMERGENCY_KEYWORDS.some((kw) => normalized.includes(normalizeArabicText(kw)));
}

